"""
高效的模型推理引擎。

一切围绕 token 序列工作：
- 用户可以向引擎发送 token 序列
- 引擎返回下一个 token

注意事项：
- 引擎对分词一无所知，纯粹处理 token ID 序列。
- 整个设计尽可能高效。
"""

